const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Whether the decoder can read anything here: { ok: true }, or an error reply.
async function decoderReady() {
  startDecoder();
  const w = decoder.current;
  if (!w) return { type: 'error', code: decoder.stopped ? 'stopped' : 'no-reader' };
  if (w.failed || !w.worker) return { type: 'error', code: 'no-reader' };
  const ok = await Promise.race([w.ready, sleep(READY_TIMEOUT_MS).then(() => false)]);
  if (!ok || w.failed) return { type: 'error', code: 'no-reader' };
  if (w.wasm === false) return { type: 'error', code: 'no-wasm' };
  return { ok: true, w };
}

// Sends one job to the decoder worker: a picture's bytes, or (stage 3) one camera frame's pixels.
// The buffer is handed over, not copied, so the page keeps no copy of it.
async function decodeWith(message, buffer, timeoutMs) {
  const ready = await decoderReady();
  if (!ready.ok) return ready;
  const { w } = ready;
  const id = ++decoder.seq;
  return new Promise((resolve) => {
    const timer = setTimeout(() => {
      // A job that keeps the decoder busy this long is stopped; the spare reads the next.
      stopDecoder(w);
      resolve({ type: 'error', id, code: decoder.current ? 'slow' : 'slow-last' });
    }, timeoutMs);
    w.pending.set(id, (msg) => {
      clearTimeout(timer);
      resolve(msg.code === 'slow' ? { ...msg, code: decoder.current ? 'slow' : 'slow-last' } : msg);
    });
    w.worker.postMessage({ ...message, id, buffer }, [buffer]);
  });
}

const decodeBuffer = (buffer, mime) => decodeWith({ type: 'decode', mime }, buffer, DECODE_TIMEOUT_MS);

function errorText(msg) {
  const d = msg.detail || {};
  switch (msg.code) {
    case 'not-image': return PIC.notImage;
    case 'too-large': return PIC.tooLarge;
    case 'too-many-pixels': return PIC.tooManyPixels(fmtInt(((d.width || 0) * (d.height || 0)) / 1e6));
    case 'unsupported': return PIC.unsupported(String(d.type || 'unknown').toUpperCase());
    case 'no-wasm':
    case 'no-reader': return PIC.noReader;
    case 'slow': return PIC.slow;
    case 'slow-last': return inApp() ? PIC.slowLastApp : PIC.slowLast;
    case 'stopped': return inApp() ? PIC.stoppedApp : PIC.stopped;
    default: return PIC.failed;
  }
}

// Reads one picture file. Only its bytes are used: never its name, never an address.
async function readPicture(file, note = '') {
  if (!file) return;
  stopCamera();
  $('input-card').classList.remove('is-dropping');
  const picId = ++state.picId;
  // A link the previous picture put in the box goes with that picture.
  const fromOld = state.pictureText !== null && $('link-input').value === state.pictureText;
  hidePicture();
  if (fromOld) {
    $('link-input').value = '';
    update();
  }
  say('');
  // The status line is a live region: it is read out once, with no second announcement.
  picStatus(PIC.reading);
  let reply;
  if (file.size > MAX_PICTURE_BYTES) reply = { type: 'error', code: 'too-large' };
  else {
    let buffer = null;
    try {
      buffer = await file.arrayBuffer();
    } catch {
      reply = { type: 'error', code: 'failed' };
    }
    if (buffer) reply = await decodeBuffer(buffer, file.type || '');
  }
  if (picId !== state.picId) return; // a newer picture came in meanwhile
  if (reply.type === 'error') {
    picStatus(errorText(reply), { error: true });
    return;
  }
  if (!reply.codes.length) {
    picStatus(PIC.none, { error: true });
    return;
  }
  showPicture(file, reply, note);
}

// The codes in reading order: top to bottom, then left to right, by where they sit once the
// picture is turned the way the camera meant.
function placed(codes, image) {
  const pts = (c) => ['topLeft', 'topRight', 'bottomRight', 'bottomLeft'].map((k) => orientPoint(c.position[k], image.width || 0, image.height || 0, image.orientation || 1));
  return codes.map((c) => ({ ...c, points: c.position ? pts(c) : null }))
    .map((c) => ({ ...c, top: c.points ? Math.min(...c.points.map((p) => p.y)) : 0, left: c.points ? Math.min(...c.points.map((p) => p.x)) : 0 }))
    .sort((a, b) => (Math.abs(a.top - b.top) > 24 ? a.top - b.top : a.left - b.left));
}

// Whether a code holds something private: a secret, or any detail hidden behind Show (a Wi-Fi
// password, a booking reference). Such a code is never drawn again on the page: a screenshot
// would carry it, whatever the card hides.
const isPrivate = (p) => p.secret || p.fields.some((f) => f.secret);
// Codes whose outline covers the whole symbol, so painting over it leaves nothing to read. A
// barcode's outline can be a single line across it, so a private barcode is never drawn.
const TWO_D = /^(QRCode|MicroQRCode|RMQRCode|rMQRCode|Aztec|DataMatrix|PDF417|MaxiCode)/;

// The web addresses of a code that are not already shown, whole, as one of its details: those
// get their Check this link button beside the detail instead.
function linkPlaces(p) {
  const inField = new Map();
  const rest = [];
  p.links.forEach((link, j) => {
    const f = p.fields.findIndex((x) => !x.secret && (x.value === link || `https://${x.value}` === link));
    if (f >= 0 && !inField.has(f)) inField.set(f, j);
    else rest.push(j);
  });
  return { inField, rest };
}

// Shows the codes read from a picture, or (stage 3, source 'camera', file null) from one camera
// frame. A camera frame is never drawn: it may show the room or the person holding the phone, and
// CheckLink keeps no frame to draw from.
function showPicture(file, reply, note, source = 'picture') {
  const camera = source === 'camera';
  const codes = placed(reply.codes, reply.image);
  const payloads = codes.map((c) => inspect(c.text, { bytes: c.bytes, format: c.format, contentType: c.contentType }));
  const links = [...new Set(payloads.flatMap((p) => p.links))];
  // Whether a code's card shows a sign-in link or a link with personal details (SEC-10).
  const personal = links.some((l) => {
    const x = analyse(l);
    const why = personalReasons(x, x.defaultRemoved);
    return !!(why.original || why.clean);
  });
  state.picture = { codes, payloads, links, personal };
  state.pictureSource = source;
  $('picture-title').textContent = camera ? 'From the camera' : 'From your picture';
  const n = codes.length;
  const only = n === 1 && payloads[0].kind === 'web' ? payloads[0].links[0] : null;
  const holds = camera ? 'The camera found' : 'This picture holds';
  // One code with a web address: the link's own summary below says that nothing has been opened,
  // so this card does not say it a second time (interface review M3).
  $('picture-summary').textContent = n === 1
    ? `${holds} one ${payloads[0].formatLabel}.${only ? '' : ' Nothing has been opened.'}`
    : `${holds} ${fmtInt(n)} codes. Each one is described below. Nothing has been opened.`;
  const priv = payloads.map(isPrivate);
  const coverable = priv.every((x, i) => !x || (codes[i].points && TWO_D.test(codes[i].format || 'QRCode')));
  const drawIt = !camera && (!priv.some(Boolean) || (n > 1 && priv.some((x) => !x) && coverable));
  const notices = [];
  if (n > 1) notices.push(camera ? PIC.severalCamera : PIC.several);
  if (n >= MAX_CODES) notices.push(PIC.capped(MAX_CODES));
  if (priv.some(Boolean) && !camera) {
    if (drawIt) {
      const nums = priv.map((x, i) => (x ? `Code ${i + 1}` : null)).filter(Boolean);
      notices.push(PIC.covered(nums.length > 1 ? `${nums.slice(0, -1).join(', ')} and ${nums.at(-1)}` : nums[0]));
    } else notices.push(PIC.notShown);
  }
  const worst = payloads.reduce((t, p, i) => (priv[i] && p.tier === 'stop' ? 'stop' : t), 'check');
  setNotice($('picture-notice'), notices.length ? { tier: priv.some(Boolean) ? worst : 'check', text: notices.join(' ') } : null);
  $('code-list').replaceChildren(...payloads.map((p, i) => codeItem(p, i, n, only !== null)));
  syncSecret();
  syncLinkSecure();
  $('picture-card').hidden = false;
  $('clear-btn').hidden = false;
  picStatus(note);
  if (drawIt) drawPicture(file, codes, reply.image, priv);
  else $('picture-view').hidden = true;
  const said = camera ? 'Code found and the camera is off.' : 'Picture read:';
  if (camera) {
    // Focus was on Stop camera, which has gone: it moves to the heading of what was found.
    $('picture-title').focus({ preventScroll: true });
  }
  if (only) {
    // One code with a web address: its link gets the full analysis straight away. From a picture
    // the page goes to that analysis; from the camera it goes to the card whose heading now holds
    // focus, so focus is never left above the screen (interface review M3). The style sheet
    // decides whether the scroll is smooth: never under reduced motion (L3).
    state.pictureText = only;
    useText(only, `${said} ${camera ? 'One' : 'one'} code with a web address. Its link is checked below.`, { focus: false });
    (camera ? $('picture-card') : $('summary-card')).scrollIntoView({ block: 'start' });
    return;
  }
  const kinds = payloads.map((p) => p.title.replace(/^(A|An) /, (m) => m.toLowerCase())).join('; ');
  const what = n === 1 ? kinds : `${fmtInt(n)} codes: ${kinds}`;
  announce(camera ? `${said} It holds ${what}.` : `${said} ${what}.`);
  $('picture-card').scrollIntoView({ block: 'start' });
}

// What a web code's own link holds that needs checking, for the code's card: the short form of a
// look-alike note, or how many things there are to check. Null when there is nothing (interface
// review H2: the card said "Good to know: A web address" over a look-alike).
function webCodeNote(p) {
  if (p.kind !== 'web' || !p.links.length) return null;
  const a = analyse(p.links[0]);
  if (!a.found) return null;
  const checks = a.warnings.filter((w) => w.tier === 'check' || w.tier === 'stop');
  if (!checks.length) return null;
  const look = lookAlikeWarning(a);
  return {
    tier: checks.some((w) => w.tier === 'stop') ? 'stop' : 'check',
    text: look && look.short ? look.short : `This address has ${plural(checks.length, 'thing', 'things')} to check.`,
  };
}

// A web address in a code, with the letters from another alphabet boxed when its own analysis
// names them (interface review M1).
function codeLinkNodes(link) {
  let a = null;
  try {
    a = analyse(link);
  } catch { /* shown as it is */ }
  return addrNodes(link, a && a.found && !a.wrappers.length && a.link === link ? boxFor(a, a.link, a.bare, a.hostAsWritten) : null);
}

// One code: what it is in plain words, its details (secrets hidden), notes, the addresses in
// it (each checked only when asked), and its own text. A Stop code says what is at stake
// before its details and buttons.
function codeItem(p, i, n, checkedBelow) {
  const id = `code-${i}`;
  const web = webCodeNote(p);
  const tier = web && (web.tier === 'stop' || p.tier === 'info') ? web.tier : p.tier;
  const colour = TIER_COLOUR[tier];
  const from = n > 1 ? ` from code ${i + 1}` : '';
  const { inField, rest } = linkPlaces(p);
  const fields = p.fields.length ? h('dl', { class: 'cl-fields' }, p.fields.map((f, j) => fieldRow(p, f, i, j, from, inField.get(j)))) : null;
  const notes = p.warnings.length ? h('ul', { class: 'cl-notes' }, p.warnings.map(noteItem)) : null;
  const links = rest.length ? h('ul', { class: 'cl-extra-list cl-code-links' }, rest.map((j) => {
    const link = p.links[j];
    let goes = null;
    if (n > 1) {
      // Beside other codes, each address says who owns it, so example.com and evil.example do
      // not look alike until each is checked.
      try {
        const host = new URL(link).hostname;
        const info = domainInfo(host);
        goes = h('p', { class: 'cl-goes cl-code-goes' }, 'Goes to ', h('span', { class: 'cl-host cl-addr' }, addrNodes(info && info.domain ? info.domain : host)), '.');
      } catch { /* not readable as an address: no line */ }
    }
    return h('li', { class: 'cl-extra-item' },
      h('p', { class: 'cl-help', text: p.kind === 'web' ? 'The web address in this code:' : 'A web address in this code:' }),
      h('p', { class: 'cl-link cl-addr', id: `${id}-link-${j}` }, codeLinkNodes(link)),
      goes,
      checkedBelow
        ? null
        : h('button', { type: 'button', class: 'btn btn-secondary cl-btn-small', dataset: { use: 'code-link', code: String(i), link: String(j) }, 'aria-describedby': `${id}-link-${j}`, 'aria-label': n > 1 ? `Check this link${from}` : null, text: 'Check this link' }));
  })) : null;
  // The code's own text is offered only when nothing in it is hidden (a Wi-Fi password would
  // otherwise show in full there).
  const raw = !isPrivate(p) && p.text && p.kind !== 'web'
    ? h('details', { class: 'cl-code-text' },
      h('summary', { text: 'The text in the code' }),
      h('p', { class: 'cl-addr' }, addrNodes(p.text)),
      p.truncated ? h('p', { class: 'cl-help', text: `The code holds ${fmtInt(p.length)} characters; the first ${fmtInt(p.text.length)} are shown.` }) : null)
    : null;
  // A web code says what its link holds that needs checking, at that tier; one whose link is
  // checked below says so instead of repeating "A web address. Nothing has been opened."
  let summary = p.summary;
  if (web) summary = `${web.text} ${checkedBelow ? 'Details below, under Things to know.' : 'Check this link for the details.'}`;
  else if (checkedBelow && p.kind === 'web' && p.summary === 'A web address. Nothing has been opened.') summary = 'Its link is checked below.';
  return h('li', { class: 'cl-code', id, dataset: colour ? { kind: p.kind, tier: colour } : { kind: p.kind } },
    h('h3', { class: 'cl-code-title' }, n > 1 ? `Code ${i + 1}: ` : '', p.title),
    h('p', { class: 'cl-code-format', text: p.formatLabel }),
    h('p', { class: 'cl-code-summary' }, tierWord({ tier }), ' ', ...noteText(summary)),
    ...(p.tier === 'stop' ? [notes, fields] : [fields, notes]),
    links, raw,
    h('p', { class: 'cl-status', id: `${id}-status`, role: 'status', 'aria-live': 'polite' }));
}

// A hidden value: the dots are not read out by screen readers, only the word.
