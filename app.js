// Everything happens in this page; nothing is sent anywhere. The page policy forbids
// network requests, inline scripts and inline styles, which shapes this file:
//  * the link and the text around it are untrusted, so they are only ever written with
//    textContent or as text nodes, never as HTML, and never into an attribute
//  * invisible and direction-changing characters in an address are drawn as visible marks
//    (U+202E and so on), so they cannot reorder or hide the address on screen; what is
//    copied, shared and opened is always the engine's own text
//  * no element ever links to the analysed address: Go to opens the clean link with
//    window.open only when it is pressed, and for a link with something to check only
//    after a confirmation that repeats the host and the reasons. The one mailto: link
//    ("Did CheckLink break your link? Email us") carries the links only as text in the
//    body of a message the person checks and sends from their own email app, and leaves
//    them out when they hold anything personal (reportMail in the engine)
//  * nothing is stored: no localStorage, no cookies, no history. The one exception is not in
//    this file: the first-run notice (gate.js, generated by build-gates.py) keeps one flag in
//    localStorage once it is closed
//  * pictures (stage 2) are read by the decoder worker (src/qr-worker.js), which the page
//    starts while it loads, so reading a picture never fetches anything; what a code holds is
//    described by src/qr-inspect.js and shown as text, never as a live link. A web address in
//    a code goes into the box and gets the full link analysis; secrets stay hidden until Show
//    is pressed, and copying one asks first
//  * the camera (stage 3) is asked for only when Scan with camera is pressed. A few times a second
//    one frame of the preview is drawn on a canvas that is never shown, and its pixels go to the
//    same decoder worker; nothing is recorded or kept. The camera stops the moment a code is
//    found, on Stop camera or Escape, when the page is hidden or left, when the person types,
//    pastes or chooses a picture, and after two minutes without a code
//  * inside the CheckLink Android app (stage 4) the same page runs in a WebView, and
//    window.CLAndroid exists (android/web-overlay/android-bridge.js, loaded only in the APK).
//    Only then do Copy, Share and Go to go through the app, text and pictures shared into the
//    app arrive as window events, and the page tells the app while the camera card or a
//    secret is on screen, so Android keeps it out of screenshots. Every such hook asks
