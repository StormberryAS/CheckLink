function schedule(ms) {
  clearTimeout(state.timer);
  state.timer = setTimeout(() => update(), ms);
}

// The line a screen reader hears when a new analysis appears. Notes to check are counted, and a
// look-alike is said in its short form, so it is heard without reading down to Things to know.
function analysisLine(a) {
  if (!a.found) return $('summary-line').textContent;
  const kept = keptWrapperIndex(a, state.removed);
  const ticked = a.parts.filter((p) => state.removed.has(p.id) && !lockedBy(p, kept)).length;
  let line;
  if (!a.parts.length) line = a.untouched ? 'Link checked: CheckLink leaves this link exactly as it is.' : 'Link checked: nothing to remove.';
  else line = `Link checked: ${plural(a.parts.length, 'part', 'parts')} found, ${fmtInt(ticked)} ticked to remove.`;
  const checks = a.warnings.filter((w) => w.tier === 'check' || w.tier === 'stop').length;
  if (!checks) return line;
  const look = lookAlikeWarning(a);
  return `${line} ${plural(checks, 'thing', 'things')} to check${look && look.short ? `: ${lowerFirst(look.short)}` : '.'}`;
}

// Reads the box. prefix, when given, is said before the line about the analysis.
function update(prefix = '') {
  clearTimeout(state.timer);
  state.timer = 0;
  const text = $('link-input').value;
  if (text === state.lastInput) return;
  state.lastInput = text;
  // Any change to the box makes a QR code on show out of date.
  closeQr();
  // The picture's codes stay while the box holds one of their addresses; typing something
  // else means the person has moved on, and they go.
  if (state.picture && text !== state.pictureText && !state.picture.links.includes(text.trim())) hidePicture();
  $('clear-btn').hidden = !text && !state.picture;
  say('');
  if (!text.trim()) {
    state.analysis = null;
    state.parts = new Map();
    state.kept = new Map();
    state.removed = new Set();
    $('result').hidden = true;
    syncLinkSecure();
    return;
  }
  const a = analyse(text);
  const prev = state.analysis;
  const sameLink = prev && prev.found && a.found && prev.link === a.link;
  // The same link again (more text typed around it): the choices made so far stay.
  if (sameLink) {
    const ids = new Set([...a.parts.map((p) => p.id), ...a.kept.map((k) => k.id)]);
    state.removed = new Set([...state.removed].filter((id) => ids.has(id)));
  } else {
    state.removed = new Set(a.defaultRemoved);
  }
  state.analysis = a;
  state.parts = new Map(a.parts.map((p) => [p.id, p]));
  state.kept = new Map(a.kept.map((k) => [k.id, k]));
  renderAll();
  syncLinkSecure();
  if (!sameLink || prefix) announce([prefix, analysisLine(a)].filter(Boolean).join(' '));
}

// The analysis of what is in the box right now: a press that comes before the pause after
// typing acts on the new text, never on the analysis of the old one.
function current() {
  if ($('link-input').value !== state.lastInput) update();
  return state.analysis;
}

// focus: false for a link read from a picture, so a phone does not open its keyboard.
function useText(text, message, { focus = true } = {}) {
  const input = $('link-input');
  input.value = text;
  update(message);
  if (focus) input.focus();
}

