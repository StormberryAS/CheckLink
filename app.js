// Two decoder workers start while the page loads (see init), so their files arrive with the
// page: the one in use and a spare. A picture that takes too long ends the worker reading it and
// the spare takes over, so the next picture is read without fetching anything. With no spare
// left, the reader stays stopped until the page is loaded again, rather than fetching its files
// after the page has loaded.
const decoder = { current: null, spare: null, started: false, stopped: false, seq: 0 };

function makeWorker() {
  const w = { worker: null, ready: null, wasm: null, failed: false, pending: new Map() };
  let resolveReady;
  w.ready = new Promise((r) => { resolveReady = r; });
  try {
    const worker = new Worker(new URL('./src/qr-worker.js?v=d6f9fb01', import.meta.url), { type: 'module' });
    worker.addEventListener('message', (ev) => {
      const msg = ev.data || {};
      if (msg.type === 'ready') {
        w.wasm = msg.wasm === true;
        resolveReady(true);
        return;
      }
      const done = w.pending.get(msg.id);
      if (done) {
        w.pending.delete(msg.id);
        done(msg);
      }
    });
    // A browser without module workers, or a worker that cannot load, ends up here.
    worker.addEventListener('error', (ev) => {
      ev.preventDefault();
      w.failed = true;
      resolveReady(false);
      for (const [id, done] of w.pending) done({ type: 'error', id, code: 'no-reader' });
      w.pending.clear();
    });
    w.worker = worker;
  } catch {
    w.failed = true;
    resolveReady(false);
  }
  return w;
}

function startDecoder() {
  if (decoder.started) return;
  decoder.started = true;
  decoder.current = makeWorker();
  decoder.spare = makeWorker();
}

// Ends a worker that took too long; the spare, if any, takes its place.
function stopDecoder(w) {
  if (w.worker) w.worker.terminate();
  w.worker = null;
  w.failed = true;
  if (decoder.current === w) {
    decoder.current = decoder.spare;
    decoder.spare = null;
    if (!decoder.current) decoder.stopped = true;
  }
  for (const [id, done] of w.pending) done({ type: 'error', id, code: 'slow' });
  w.pending.clear();
}

