// Shortens a long piece of a link for a label, keeping its start and its end.
function shortened(s, max = 48) {
  const chars = Array.from(String(s));
  if (chars.length <= max) return String(s);
  return `${chars.slice(0, max - 14).join('')}\u2026${chars.slice(-12).join('')}`;
}

// Text of an address as nodes: ordinary runs as text, and each invisible or
// direction-changing character as a small visible mark with its code point. box, when given
// ({ range: [start, end], chars: Map of letter -> alphabet }), puts a box round each letter from
// another alphabet that a look-alike note names, where it falls inside the host (offset is where
// text starts in the link): such a name looks exactly like the real one, boxed it does not
// (interface review M1). The box is drawn by the style sheet only, so copying gets the letters.
function addrNodes(text, box = null, offset = 0) {
  const out = [];
  let pos = offset;
  for (const c of invisibleChunks(text)) {
    const start = pos;
    pos += c.text.length;
    if (c.invisible) {
      out.push(h('span', { class: 'cl-invis', title: c.label, text: c.label.split(' ')[0] }));
      continue;
    }
    if (!box || pos <= box.range[0] || start >= box.range[1]) {
      out.push(c.text);
      continue;
    }
    let run = '';
    let i = start;
    for (const ch of c.text) {
      const script = i >= box.range[0] && i < box.range[1] ? box.chars.get(ch.toLowerCase()) : null;
      if (script) {
        if (run) out.push(run);
        run = '';
        out.push(h('span', { class: 'cl-foreign', title: `${script} letter` }, ch));
      } else run += ch;
      i += ch.length;
    }
    if (run) out.push(run);
  }
  return out;
}

// The box for addrNodes: the host of a link as written, and the letters the analysis names.
function boxFor(a, link, bare, written) {
  const chars = boxChars(a);
  if (!chars) return null;
  const range = hostRange(link, bare, written);
  return range ? { range, chars } : null;
}

