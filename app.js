// Makes the code, reads it back with the decoder worker and shows it only when the reading is
// exactly the text it holds. The picture is the one Save, Share and Copy hand on, byte for byte.
async function makeQrCode() {
  const a = current();
  if (!a || !a.found) return;
  const removed = new Set(state.removed);
  if (qrRefusal(a, removed)) {
    renderChoice();
    return;
  }
  const clean = a.clean(removed);
  if (state.qr && state.qr.clean === clean) {
    showQr();
    return;
  }
  const payload = qrText(a.openUrl(removed));
  const qr = payload && makeQr(payload.text);
  if (!qr) {
    say(QR.noMatch);
    return;
  }
  const png = qrPng(qr);
  const run = ++qrRun;
  say(QR.making);
  // The worker takes the bytes it is given; it gets a copy, and the page keeps the picture.
  const reply = await decodeWith({ type: 'decode', mime: 'image/png' }, png.slice().buffer, DECODE_TIMEOUT_MS);
  if (run !== qrRun) return;
  if (reply.type === 'error') {
    say(['no-wasm', 'no-reader', 'stopped', 'slow', 'slow-last'].includes(reply.code) ? qrReaderLine(reply.code) : QR.noMatch);
    return;
  }
  const want = new TextEncoder().encode(payload.text);
  const read = reply.codes;
  const same = read.length === 1 && read[0].format === 'QRCode' && read[0].text === payload.text
    && read[0].bytes.length === want.length && want.every((b, i) => read[0].bytes[i] === b);
  if (!same) {
    say(QR.noMatch);
    return;
  }
  say('');
  state.qr = { clean, text: payload.text, host: payload.host, ascii: payload.ascii, scheme: !/^https?:\/\//i.test(clean), qr, png };
  showQr();
}

