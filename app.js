  if (linkIndex !== undefined) buttons.push(h('button', { type: 'button', class: 'btn btn-secondary cl-btn-small', dataset: { use: 'code-link', code: String(i), link: String(linkIndex) }, 'aria-describedby': `${id}-v`, 'aria-label': `Check this link${from}`, text: 'Check this link' }));
