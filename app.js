async function copyField(i, j) {
  const p = state.picture && state.picture.payloads[i];
  const f = p && p.fields[j];
  if (!f) return;
  const text = f.copyValue ?? f.value;
  // A secret from a Stop code is copied only after a confirmation (spec section 3).
  if (f.secret && p.tier === 'stop') {
    const dialog = $('copy-dialog');
    state.pendingCopy = { i, text, label: f.label, from: document.activeElement };
    if (typeof dialog.showModal === 'function') {
      dialog.showModal();
      return;
    }
    // eslint-disable-next-line no-alert
    if (!window.confirm('Copy the secret? Whoever gets what you copy has the secret.')) {
      state.pendingCopy = null;
      return;
    }
  }
  codeStatus(i, (await copyText(text, !!f.secret)) ? `Copied: ${f.label}.` : 'It could not be copied. Select it and copy it yourself.');
}

async function toggleShow(btn) {
  const i = Number(btn.dataset.code);
  const j = Number(btn.dataset.field);
  const f = state.picture && state.picture.payloads[i] && state.picture.payloads[i].fields[j];
  const value = document.getElementById(`code-${i}-f${j}-v`);
  if (!f || !value) return;
  const show = btn.getAttribute('aria-pressed') !== 'true';
  // In the Android app the screen is protected first, and the secret appears only once the app
  // says screenshots and the recent-apps thumbnail can no longer catch it. Without that answer it
  // stays hidden and the page says why. On the website inApp() is false and nothing waits.
  if (show && inApp()) {
    if (btn.dataset.waiting) return;
    btn.dataset.waiting = 'true';
    const ok = await secureScreen('secret', true);
    delete btn.dataset.waiting;
    if (!value.isConnected || btn.getAttribute('aria-pressed') === 'true') {
      syncSecret();
      return;
    }
    if (!ok) {
      syncSecret();
      codeStatus(i, APP_SECRET_UNPROTECTED);
      return;
    }
  }
  btn.setAttribute('aria-pressed', show ? 'true' : 'false');
  btn.textContent = show ? 'Hide' : 'Show';
  const from = state.picture.payloads.length > 1 ? ` from code ${i + 1}` : '';
  btn.setAttribute('aria-label', `${show ? 'Hide' : 'Show'} ${f.label}${from}`);
  value.dataset.shown = show ? 'true' : 'false';
  value.replaceChildren(...(show ? addrNodes(f.value) : maskNodes()));
  if (!show) syncSecret();
}

// The picture itself, small, with each code found outlined and numbered, so a sticker over a
// real code can be told apart. Drawn from the file on this device; nothing is read back.
async function drawPicture(file, codes, image, priv = []) {
  const canvas = $('picture-view');
  canvas.hidden = true;
  if (typeof createImageBitmap !== 'function') return;
  let bmp;
  try {
    bmp = await createImageBitmap(file);
  } catch {
    return;
  }
  if (!state.picture || state.picture.codes !== codes) return;
  // The card's own content width (its padding grows with the text size), and on a phone a
  // shorter picture, so the codes' cards and the link analysis are not pushed far down.
  const card = $('picture-card');
  const cs = getComputedStyle(card);
  const avail = Math.max(120, (card.clientWidth || 600) - (parseFloat(cs.paddingLeft) || 0) - (parseFloat(cs.paddingRight) || 0) - 2);
  const maxH = window.matchMedia('(max-width: 480px)').matches ? 180 : 360;
  const scale = Math.min(1, avail / bmp.width, maxH / bmp.height);
  const w = Math.max(1, Math.round(bmp.width * scale));
  const hgt = Math.max(1, Math.round(bmp.height * scale));
  const dpr = Math.min(window.devicePixelRatio || 1, 3);
  canvas.width = Math.round(w * dpr);
  canvas.height = Math.round(hgt * dpr);
  // Only the width is set: the height follows from the picture's own shape.
  canvas.style.width = `${w}px`;
  canvas.style.height = '';
  const ctx = canvas.getContext('2d');
  ctx.scale(dpr, dpr);
  ctx.drawImage(bmp, 0, 0, w, hgt);
  const shown = orientedSize(image.width || bmp.width, image.height || bmp.height, image.orientation || 1);
  const sx = w / (shown.width || bmp.width);
  const sy = hgt / (shown.height || bmp.height);
  const css = getComputedStyle(document.documentElement);
  const accent = css.getPropertyValue('--accent-strong').trim() || '#d946ef';
  const ink = css.getPropertyValue('--on-accent').trim() || '#0c0a12';
  codes.forEach((c, i) => {
    if (!c.points) return;
    const pts = c.points.map((p) => ({ x: p.x * sx, y: p.y * sy }));
    if (priv[i]) {
      // A code with private details is painted over, a quarter wider than its outline on every
      // side, so nothing of it can be read from a screenshot.
      const cx0 = pts.reduce((a, q) => a + q.x, 0) / pts.length;
      const cy0 = pts.reduce((a, q) => a + q.y, 0) / pts.length;
      ctx.fillStyle = ink;
      ctx.beginPath();
      pts.forEach((q, k) => {
        const x = cx0 + (q.x - cx0) * 1.5;
        const y = cy0 + (q.y - cy0) * 1.5;
        if (k) ctx.lineTo(x, y);
        else ctx.moveTo(x, y);
      });
      ctx.closePath();
      ctx.fill();
    }
    ctx.lineWidth = 3;
    ctx.strokeStyle = accent;
    ctx.beginPath();
    pts.forEach((p, k) => (k ? ctx.lineTo(p.x, p.y) : ctx.moveTo(p.x, p.y)));
    ctx.closePath();
    ctx.stroke();
    if (codes.length > 1) {
      const cx = Math.max(14, Math.min(w - 14, pts[0].x));
      const cy = Math.max(14, Math.min(hgt - 14, pts[0].y));
      ctx.fillStyle = accent;
      ctx.beginPath();
      ctx.arc(cx, cy, 13, 0, Math.PI * 2);
      ctx.fill();
      ctx.fillStyle = ink;
      ctx.font = '700 15px system-ui, sans-serif';
      ctx.textAlign = 'center';
      ctx.textBaseline = 'middle';
      ctx.fillText(String(i + 1), cx, cy + 1);
    }
  });
  if (typeof bmp.close === 'function') bmp.close();
  const coveredNote = priv.some(Boolean) ? ' Codes with private details are painted over.' : '';
  canvas.setAttribute('aria-label', codes.length > 1
    ? `Your picture, with the ${fmtInt(codes.length)} codes CheckLink found outlined and numbered 1 to ${fmtInt(codes.length)} in reading order.${coveredNote}`
    : 'Your picture, with the code CheckLink found outlined.');
  canvas.hidden = false;
}

