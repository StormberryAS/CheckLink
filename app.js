const cam = { stream: null, run: 0, timer: 0, limit: 0, until: 0, canvas: null, hidden: 0, devices: [], deviceId: null };

// Whether the camera is on, or being asked for.
const cameraOn = () => !!cam.stream || !$('camera-card').hidden;

// The two-minute limit, as a timer of its own from the moment the camera is given: it holds even
// for a camera that never sends a picture, whose preview never starts playing and so never reaches
// the frame loop (camera review C1). The frame loop checks cam.until as well.
function startLimit(run) {
  clearTimeout(cam.limit);
  cam.until = Date.now() + SCAN_FOR_MS;
  cam.limit = setTimeout(() => {
    if (run === cam.run && cameraOn()) stopCamera(CAM.timeout, { error: true, focus: true });
  }, SCAN_FOR_MS);
}

// The preview takes the shape of what the camera sends, so the whole frame the decoder reads is
// seen, not a crop of it (interface review L4). Set through the style sheet's own properties.
function fitPreview() {
  const video = $('cam-video');
  const frame = video.parentElement;
  if (video.videoWidth && video.videoHeight) {
    frame.style.setProperty('--cam-w', String(video.videoWidth));
    frame.style.setProperty('--cam-h', String(video.videoHeight));
  } else {
    frame.style.removeProperty('--cam-w');
    frame.style.removeProperty('--cam-h');
  }
}

// A camera interface exists (a secure page in a browser that has getUserMedia). The camera itself
// is not asked for, and no device is listed, until Scan with camera is pressed.
function cameraInterface() {
  try {
    return !!(window.isSecureContext && navigator.mediaDevices && typeof navigator.mediaDevices.getUserMedia === 'function');
  } catch {
    return false;
  }
}

// Whether the site's own Permissions-Policy lets this page use the camera (the zone sends
// camera=(); check.stormberry.as needs camera=(self), see NOTICE). Browsers without the
// interface to ask are assumed to allow it, and getUserMedia then says otherwise if not.
function siteAllowsCamera() {
  try {
    const policy = document.permissionsPolicy || document.featurePolicy;
    if (policy && typeof policy.allowsFeature === 'function') return policy.allowsFeature('camera') !== false;
  } catch { /* no way to ask */ }
  return true;
}

