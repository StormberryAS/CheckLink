// Tells the app that the camera card or a secret starts or stops being on screen, so it can keep
// screenshots and the recent-apps thumbnail out (FLAG_SECURE). Turning on resolves to true only
// once the app has confirmed it; anything else (no answer in time, no bridge) resolves to false and
// the caller shows nothing (fail closed). On the website, at once to true.
// appSecure[reason]: null while off, or the answer to the request that turned it on. 'link'
// (stage 4b, SEC-10) is best effort: syncLinkSecure asks, and nothing waits for the answer.
const appSecure = { camera: null, secret: null, link: null };
// Two animation frames: by then the page without the secret or the camera card has been drawn.
const afterPaint = (fn) => requestAnimationFrame(() => requestAnimationFrame(fn));
function secureScreen(reason, on) {
  if (!inApp()) return Promise.resolve(true);
  const app = android();
  if (!app) return Promise.resolve(!on);
  if (on) {
    if (!appSecure[reason]) {
      const asked = Promise.resolve(app.secure(reason, true)).then((ok) => ok === true, () => false).then((ok) => {
        // Not confirmed: nothing is shown for this reason, and the app is told to drop it in case
        // its answer was only late.
        if (!ok && appSecure[reason] === asked) {
          appSecure[reason] = null;
          app.secure(reason, false);
        }
        return ok;
      });
      appSecure[reason] = asked;
    }
    return appSecure[reason];
  }
  // Lifted only after the change has been drawn, so a screenshot taken at that moment cannot catch
  // the last frame with the secret or the camera card; skipped when it is needed again by then.
  if (appSecure[reason]) {
    appSecure[reason] = null;
    afterPaint(() => {
      if (!appSecure[reason]) app.secure(reason, false);
    });
  }
  return Promise.resolve(true);
}
