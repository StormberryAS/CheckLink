//    confirmed that screenshots are blocked; without that answer the page says so instead. A
//    sign-in link or a link with personal details asks for the same block, best effort: it stays
//    on screen whatever the app answers (stage 4b, SEC-10)
//  * a QR code of the clean link (stage 4b): Make a QR code draws it with src/qr-make.js as one
//    inline SVG path, black on white, and offers its picture, qr-code.png, to save, share and (on
