#!/usr/bin/env node
// Writes the declarations that let the TypeScript compiler follow CheckLink's stamped imports.
// Type checking only: nothing here is served, bundled or run by the page or the app.
//
// The page loads its modules with a content stamp, `import { analyse } from './src/link-core.js?v=108881e2'`
// (bump_assets.py writes the stamps), and the compiler cannot resolve a module name with a query in
// it. The two configurations (jsconfig.json for the page, jsconfig.worker.json for the decoder
// worker) also use `noResolve`, so the compiler reads exactly the files they list and never pulls in
// vendor/ through an import. For every stamped import in those files, this script writes one line
//
//   declare module '*/link-core.js?v=108881e2' { export * from '#cl/src/link-core.js'; }
//
// into types/stamps.d.ts (page) or types/stamps.worker.d.ts (worker): the stamped name stands for
// the real file, which the configurations map with `"paths": { "#cl/*": ["./*"] }`. A stamp changes
// whenever bump_assets.py runs, so `npm run typecheck` runs this first.
//
// Usage:  node tools/typecheck-stamps.mjs [--check]
//         --check exits 1 if a declarations file is not current, without writing.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CONFIGS = [['jsconfig.json', 'types/stamps.d.ts'], ['jsconfig.worker.json', 'types/stamps.worker.d.ts']];
// A static import or re-export with a stamp: `from './x.js?v=0123abcd'` or `import './x.js?v=0123abcd'`.
const STAMPED = /(?:\bfrom|^\s*import)\s*'(\.{1,2}\/[^'?]+\.js)\?v=([0-9a-f]{8})'/gm;

/**
 * The JavaScript files a configuration lists: plain names, and `dir/*.js` patterns, less `exclude`.
 * @param {{ include?: string[], exclude?: string[] }} config
 * @returns {string[]} paths relative to the repository root, with forward slashes
 */
function listedFiles(config) {
  /** @type {Set<string>} */
  const files = new Set();
  for (const entry of config.include || []) {
    if (!entry.endsWith('.js')) continue;
    const star = entry.indexOf('*');
    if (star < 0) {
      files.add(entry);
      continue;
    }
    const dir = posix.dirname(entry);
    const [head, tail] = posix.basename(entry).split('*');
    for (const name of readdirSync(join(ROOT, dir)).sort()) {
      if (name.startsWith(head) && name.endsWith(tail)) files.add(posix.join(dir, name));
    }
  }
  for (const entry of config.exclude || []) files.delete(entry);
  return [...files].sort();
}

/**
 * The declarations file for one configuration.
 * @param {string} configName
 * @returns {string}
 */
function render(configName) {
  const config = JSON.parse(readFileSync(join(ROOT, configName), 'utf8'));
  /** @type {Map<string, string>} pattern -> target */
  const lines = new Map();
  for (const file of listedFiles(config)) {
    const text = readFileSync(join(ROOT, file), 'utf8');
    for (const m of text.matchAll(STAMPED)) {
      const target = posix.normalize(posix.join(posix.dirname(file), m[1]));
      if (!existsSync(join(ROOT, target))) throw new Error(`${file}: ${m[1]} does not exist`);
      const pattern = `*/${posix.basename(target)}?v=${m[2]}`;
      const known = lines.get(pattern);
      if (known && known !== target) throw new Error(`${pattern} stands for both ${known} and ${target}`);
      lines.set(pattern, target);
    }
  }
  const body = [...lines].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([pattern, target]) => `declare module '${pattern}' { export * from '#cl/${target}'; }`);
  return [
    `// Generated by tools/typecheck-stamps.mjs from the stamped imports of the files ${configName} lists.`,
    '// Do not edit: run npm run typecheck, which writes it again before it checks.',
    ...body,
    '',
  ].join('\n');
}

const check = process.argv.includes('--check');
let stale = 0;
for (const [configName, out] of CONFIGS) {
  const text = render(configName);
  const path = join(ROOT, out);
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (current === text) continue;
  if (check) {
    console.error(`${relative(ROOT, path)} is not current: run node tools/typecheck-stamps.mjs`);
    stale++;
  } else {
    writeFileSync(path, text);
    console.log(`wrote ${relative(ROOT, path)}`);
  }
}
process.exit(stale ? 1 : 0);
